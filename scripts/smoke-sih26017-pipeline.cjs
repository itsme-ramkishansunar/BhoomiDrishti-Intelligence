const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { runPipeline } = require('./sih26017-pipeline.cjs');
const root = path.resolve(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bhoomidrishti-u46-'));
const input = path.join(tmp, 'input'); const output = path.join(tmp, 'output');
fs.mkdirSync(input, {recursive:true});
fs.copyFileSync(path.join(root, 'backend', 'seed-projects.json'), path.join(input, 'seed-projects.json'));
const result = runPipeline({input, output});
const r = result.report;
if (r.schemaVersion !== 'sih26017-data-pipeline-v1') throw new Error('Pipeline schema missing.');
if (r.files.length !== 1) throw new Error('Expected one fixture file.');
if (!r.files[0].sha256 || !r.files[0].bytes) throw new Error('File manifest is incomplete.');
if (!r.files[0].sheets[0].grain.primaryProjectIdCandidate) throw new Error('Project identifier candidate was not detected.');
if (!(r.files[0].sheets[0].labels.candidateFields||[]).length) throw new Error('Outcome candidate detection returned empty.');
if (r.readiness.trainingAllowed !== false || r.readiness.modelPromotionAllowed !== false) throw new Error('Safety gate accidentally opened.');
for (const f of ['SIH26017_DATA_READINESS_LATEST.json','SIH26017_DATA_READINESS_LATEST.md','SIH26017_DATA_DICTIONARY_LATEST.md','SIH26017_OUTCOME_REVIEW_LATEST.md','SIH26017_SPLIT_PLAN_LATEST.md','SIH26017_PROVENANCE_LATEST.md','DATA_AUDIT.md','DATA_DICTIONARY.md','PROVENANCE.md','MAPPING_REVIEW.md']) if (!fs.existsSync(path.join(output,f))) throw new Error(`Missing pipeline artifact: ${f}`);
console.log('SIH26017 DATA PIPELINE SMOKE PASSED');
